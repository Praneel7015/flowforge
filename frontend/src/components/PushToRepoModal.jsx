import React, { useMemo, useState } from 'react';
import axios from 'axios';
import RepoBrowser from './RepoBrowser';
import { readPlatformCredentials as readStoredCredentials } from '../utils/platformCredentials';

const SUPPORTED_PLATFORMS = ['github', 'gitlab', 'bitbucket'];
const PLATFORM_LABELS = { github: 'GitHub', gitlab: 'GitLab', bitbucket: 'Bitbucket' };

function hasCredentials(creds, platform) {
  if (!creds[platform]) return false;
  if (platform === 'bitbucket') return !!(creds[platform].username && creds[platform].appPassword);
  return !!creds[platform].token;
}

const PLATFORM_FILE_PATHS = {
  // Repo hosts
  github: '.github/workflows/ci.yml',
  gitlab: '.gitlab-ci.yml',
  bitbucket: 'bitbucket-pipelines.yml',
  // CI/CD targets (take precedence so a Jenkinsfile isn't written as a workflow yml)
  jenkins: 'Jenkinsfile',
  circleci: '.circleci/config.yml',
};

export default function PushToRepoModal({
  platform: platformProp,
  owner: ownerProp,
  repo: repoProp,
  branch: branchProp,
  yamlContent,
  cicdPlatform,
  onClose,
  onSuccess,
}) {
  const allCreds = readStoredCredentials();
  const connectedPlatforms = useMemo(
    () => SUPPORTED_PLATFORMS.filter((p) => hasCredentials(allCreds, p)),
    [allCreds]
  );

  // Standalone mode: the caller didn't pin a repo/branch (e.g. launched from the
  // Builder's YAML panel), so we let the user pick one here.
  const standalone = !repoProp || !branchProp;

  const [platform, setPlatform] = useState(platformProp || connectedPlatforms[0] || 'github');
  const [repo, setRepo] = useState(repoProp || '');
  const [repoId, setRepoId] = useState(repoProp || '');
  const [owner, setOwner] = useState(ownerProp || '');
  const [branch, setBranch] = useState(branchProp || '');

  const [mode, setMode] = useState('pr');
  const [prBranch, setPrBranch] = useState(`flowforge/pipeline-${Date.now()}`);
  const [prTitle, setPrTitle] = useState('ci: add FlowForge pipeline config');
  const [commitMessage, setCommitMessage] = useState('ci: add pipeline config via FlowForge');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [secretFindings, setSecretFindings] = useState(null);
  const [allowSecrets, setAllowSecrets] = useState(false);

  const credentials = allCreds[platform] || {};
  const resolvedFilePath =
    PLATFORM_FILE_PATHS[cicdPlatform] || PLATFORM_FILE_PATHS[platform] || '.github/workflows/ci.yml';

  const handleRepoSelect = (name, ownerFromRepo, meta) => {
    setRepo(name);
    const repoMeta = meta || (typeof ownerFromRepo === 'object' ? ownerFromRepo : null);
    const resolvedOwner = typeof ownerFromRepo === 'string' ? ownerFromRepo : repoMeta?.owner;
    // GitLab addresses projects by numeric id; GitHub/Bitbucket by name.
    setRepoId(platform === 'gitlab' ? repoMeta?.id || name : name);
    setOwner(resolvedOwner || credentials.username || credentials.workspace || '');
    setBranch('');
    setSecretFindings(null);
    setAllowSecrets(false);
  };

  const canPush = Boolean(yamlContent && repo && branch && !loading);

  const handlePush = async (overrideSecrets = false) => {
    setLoading(true);
    setError('');
    if (!overrideSecrets) setSecretFindings(null);
    try {
      const { data } = await axios.post('/api/repo/push-pipeline', {
        platform,
        credentials,
        owner,
        repo: standalone ? repoId || repo : repoProp,
        branch,
        yamlContent,
        filePath: resolvedFilePath,
        commitMessage,
        mode,
        prBranch: mode === 'pr' ? prBranch : undefined,
        prTitle: mode === 'pr' ? prTitle : undefined,
        prDescription: mode === 'pr' ? 'Pipeline configuration generated by FlowForge.' : undefined,
        targetBranch: branch,
        allowSecrets: overrideSecrets || allowSecrets,
      });
      onSuccess(data);
    } catch (err) {
      const res = err.response;
      if (res?.status === 422 && res.data?.code === 'SECRETS_DETECTED') {
        // Backend secret scanner blocked the push — surface findings and let the
        // user consciously override.
        setSecretFindings(res.data.findings || []);
        setError('');
      } else {
        setError(res?.data?.error || 'Failed to push to repository');
      }
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-[var(--ff-overlay)] p-4">
      <div className="w-full max-w-lg max-h-[90vh] overflow-y-auto rounded-2xl border border-[var(--ff-card-border)] bg-[var(--ff-sidebar-bg)] shadow-xl p-6 space-y-5">
        {/* Header */}
        <div className="flex items-start justify-between gap-3">
          <div>
            <h3 className="text-base font-semibold text-[var(--ff-text)]">Push to Repository</h3>
            <p className="text-xs text-[var(--ff-muted)] mt-0.5">
              {repo ? (
                <>
                  {repo} · {branch || '—'} · <span className="font-mono">{resolvedFilePath}</span>
                </>
              ) : (
                <>Select a repository and branch to push <span className="font-mono">{resolvedFilePath}</span></>
              )}
            </p>
          </div>
          <button
            onClick={onClose}
            className="text-[var(--ff-muted)] hover:text-[var(--ff-text)] transition-colors"
            aria-label="Close"
          >
            <svg width="16" height="16" viewBox="0 0 16 16" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round">
              <path d="M3 3l10 10M13 3L3 13" />
            </svg>
          </button>
        </div>

        {/* Standalone repo selection */}
        {standalone && (
          <div className="space-y-3">
            {connectedPlatforms.length === 0 ? (
              <div className="rounded-xl border border-amber-500/20 bg-amber-500/10 p-3 text-xs text-amber-400">
                No platforms connected. Add credentials in Settings → Platform Integrations first.
              </div>
            ) : (
              <>
                <div className="flex flex-wrap gap-2">
                  {connectedPlatforms.map((p) => (
                    <button
                      key={p}
                      onClick={() => {
                        setPlatform(p);
                        setRepo('');
                        setRepoId('');
                        setBranch('');
                        setSecretFindings(null);
                      }}
                      className={`px-3 py-1.5 rounded-lg border text-xs font-medium transition-colors ${
                        platform === p
                          ? 'border-[var(--ff-border-strong)] bg-[var(--ff-accent-soft)] text-[var(--ff-text)]'
                          : 'border-[var(--ff-card-border-strong)] bg-[var(--ff-card-bg)] text-[var(--ff-text-secondary)]'
                      }`}
                    >
                      {PLATFORM_LABELS[p]}
                    </button>
                  ))}
                </div>
                <RepoBrowser
                  platform={platform}
                  selectedRepo={repo}
                  selectedOwner={owner}
                  selectedBranch={branch}
                  onRepoSelect={handleRepoSelect}
                  onBranchSelect={setBranch}
                />
              </>
            )}
          </div>
        )}

        {/* Mode toggle */}
        <div className="grid grid-cols-2 gap-2">
          <button
            onClick={() => setMode('pr')}
            className={`rounded-xl border px-4 py-3 text-left transition-all ${
              mode === 'pr'
                ? 'border-[var(--ff-border-strong)] bg-[var(--ff-accent-soft)]'
                : 'border-[var(--ff-card-border-strong)] bg-[var(--ff-card-bg)] hover:border-[var(--ff-border-strong)]'
            }`}
          >
            <p className="text-sm font-semibold text-[var(--ff-text)]">Open PR / MR</p>
            <p className="text-xs text-[var(--ff-muted)] mt-0.5">Create a branch and open a pull request for review</p>
          </button>
          <button
            onClick={() => setMode('direct')}
            className={`rounded-xl border px-4 py-3 text-left transition-all ${
              mode === 'direct'
                ? 'border-[var(--ff-border-strong)] bg-[var(--ff-accent-soft)]'
                : 'border-[var(--ff-card-border-strong)] bg-[var(--ff-card-bg)] hover:border-[var(--ff-border-strong)]'
            }`}
          >
            <p className="text-sm font-semibold text-[var(--ff-text)]">Commit directly</p>
            <p className="text-xs text-[var(--ff-muted)] mt-0.5">
              Push straight to <span className="font-mono text-[10px]">{branch || 'branch'}</span>
            </p>
          </button>
        </div>

        {/* PR mode fields */}
        {mode === 'pr' && (
          <div className="space-y-3">
            <div>
              <label className="text-xs uppercase tracking-[0.14em] text-[var(--ff-muted)] block mb-1.5">PR Title</label>
              <input
                type="text"
                value={prTitle}
                onChange={(e) => setPrTitle(e.target.value)}
                className="ff-input px-3 py-2 text-sm"
              />
            </div>
            <div>
              <label className="text-xs uppercase tracking-[0.14em] text-[var(--ff-muted)] block mb-1.5">New Branch Name</label>
              <input
                type="text"
                value={prBranch}
                onChange={(e) => setPrBranch(e.target.value)}
                className="ff-input px-3 py-2 text-sm font-mono"
              />
            </div>
          </div>
        )}

        {/* Direct mode fields */}
        {mode === 'direct' && (
          <div>
            <label className="text-xs uppercase tracking-[0.14em] text-[var(--ff-muted)] block mb-1.5">Commit Message</label>
            <input
              type="text"
              value={commitMessage}
              onChange={(e) => setCommitMessage(e.target.value)}
              className="ff-input px-3 py-2 text-sm"
            />
          </div>
        )}

        {/* Secret scan warning */}
        {secretFindings && (
          <div className="rounded-xl border border-[var(--ff-danger)]/30 bg-[var(--ff-danger)]/10 p-3 space-y-2">
            <p className="text-sm font-semibold text-[var(--ff-danger)]">
              Potential secrets detected — push blocked
            </p>
            <ul className="text-xs text-[var(--ff-text-secondary)] space-y-1 max-h-32 overflow-y-auto">
              {secretFindings.map((f, i) => (
                <li key={i} className="font-mono">
                  line {f.line}: {f.label} <span className="opacity-70">({f.match})</span>
                </li>
              ))}
            </ul>
            <label className="flex items-center gap-2 text-xs text-[var(--ff-text-secondary)] cursor-pointer">
              <input
                type="checkbox"
                checked={allowSecrets}
                onChange={(e) => setAllowSecrets(e.target.checked)}
              />
              I understand these will be committed — push anyway
            </label>
          </div>
        )}

        {error && (
          <p className="text-sm text-[var(--ff-danger)] bg-[var(--ff-danger)]/10 border border-[var(--ff-danger)]/20 rounded-lg px-3 py-2">
            {error}
          </p>
        )}

        {/* Actions */}
        <div className="flex items-center gap-3 pt-1">
          <button
            onClick={() => handlePush(secretFindings ? allowSecrets : false)}
            disabled={!canPush || (secretFindings && !allowSecrets)}
            className="flex-1 ff-btn-primary rounded-xl py-2.5 text-sm font-semibold disabled:opacity-50"
          >
            {loading
              ? 'Pushing...'
              : secretFindings
                ? 'Push Anyway'
                : mode === 'pr'
                  ? 'Create Branch & Open PR'
                  : 'Commit to Repository'}
          </button>
          <button
            onClick={onClose}
            className="ff-btn-secondary rounded-xl px-4 py-2.5 text-sm font-medium"
          >
            Cancel
          </button>
        </div>
      </div>
    </div>
  );
}
